create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  first_name text default '',
  last_name text default '',
  email text not null unique,
  phone text default '',
  password text not null,
  group_id bigint not null default 2,
  role text not null default 'user' check (role in ('user', 'admin', 'developer')),
  is_aktif text not null default 'N',
  subscribe_newsletter boolean not null default false,
  email_verified_at timestamptz,
  verification_token text,
  token_expires_at timestamptz,
  token_version integer not null default 0,
  reset_otp text,
  reset_otp_expires_at timestamptz,
  reset_otp_attempts integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id),
  plan_title text not null default '',
  price_range text not null default '',
  plan_price_range text,
  project_title text not null,
  category text not null,
  description text not null,
  skills text not null,
  contact_name text not null,
  contact_phone text not null,
  additional_notes text not null default '',
  status text not null default 'pending' check (status in ('pending', 'approved', 'process', 'done', 'rejected')),
  reject_reason text,
  invoice_number text,
  invoice_issued_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id),
  user_id bigint not null references public.users(id),
  order_id text not null unique,
  amount numeric not null,
  status text not null default 'pending',
  snap_token text,
  snap_url text,
  paid_at timestamptz,
  transaction_id text,
  payment_type text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.project_attachments (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  file_name text not null,
  file_size bigint not null,
  file_type text not null,
  storage_path text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.pricing_plans (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  tier text not null,
  min_price numeric not null,
  max_price numeric, -- NULL = paket tanpa batas atas
  price_range text not null,
  timeline text,
  badge text,
  description text,
  upgrade_note text,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.plan_features (
  id uuid primary key default gen_random_uuid(),
  plan_id uuid not null references public.pricing_plans(id) on delete cascade,
  feature text not null,
  sort_order integer not null default 0
);

create table if not exists public.plan_not_included (
  id uuid primary key default gen_random_uuid(),
  plan_id uuid not null references public.pricing_plans(id) on delete cascade,
  feature text not null,
  sort_order integer not null default 0
);

create index if not exists projects_user_id_idx on public.projects(user_id);
create index if not exists project_attachments_project_id_idx on public.project_attachments(project_id);
create index if not exists payments_project_id_idx on public.payments(project_id);

